a=int(input(f"Введите число a:"))
b=int(input(f"Введите число b:"))
print(f"Сложение:{a+b}")
print(f"Разность:{a-b}")
print(f"Умножение:{a*b}")
if b==0:
    print(f"Результат деления равен бесконечности,частного и остатка не существует")
else:
    print(f"Частное от деления:{a//b}")
    print(f"Остаток от деления:{a%b}")
print(f"Возведение в степень:{a**b}")
if b==0:
    print(f"Результат равен бесконечности")

